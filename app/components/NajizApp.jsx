            if(i===ans){ bg="rgba(0,184,148,0.15)"; border=COLORS.teal; extra=<Check size={16} color={COLORS.teal}/>; }
            else if(i===selected){ bg="rgba(255,90,90,0.12)"; border="#ff5a5a"; extra=<X size={16} color="#ff5a5a"/>; }
